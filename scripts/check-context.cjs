const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { ContextStore, PromptDetector, checkpointMarkdown, plainText, validateCheckpoint, validateFields } = require('../dist-electron/context.js');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'asm-context-'));
const source = { id: 'session-1', kind: 'managed', provider: 'codex', name: 'API refactor', cwd: 'C:\\project' };
const fields = { title: 'API handover', goal: 'Preserve client compatibility', progress: 'Parser updated', decisions: 'Keep public API stable', blockers: 'Review timeout behavior', nextSteps: 'Run integration checks', verification: 'Unit checks passed; integration checks not run', references: 'src/api.ts' };
const file = path.join(directory, 'library.json');
const store = new ContextStore(file);
store.rememberSource(source);
assert.equal(store.state.checkpoints.length, 0);
const first = store.addAttention(source, 'Needs approval', 'inferred');
assert(first); assert.equal(store.addAttention(source, 'Needs approval', 'inferred'), null);
const manual = store.addAttention(source, 'Review architecture choice', 'manual');
assert(store.resolveAutomatic(source.id));
assert(store.state.attention.find(a => a.id === first.id).resolvedAt);
assert.equal(store.state.attention.find(a => a.id === manual.id).resolvedAt, null);
store.resolve(manual.id); assert(!store.state.attention.some(a => !a.resolvedAt));
store.notifications(true);
const original = { ...fields, id: 'checkpoint-1', source, createdAt: new Date().toISOString(), parentId: null, git: { branch: 'main', commit: 'abc', status: ' M src/api.ts', capturedAt: new Date().toISOString(), error: null }, terminalExcerpt: null };
store.addCheckpoint(original);
store.addCheckpoint({ ...original, id: 'checkpoint-2', parentId: original.id, nextSteps: 'Address review findings' });
const reopened = new ContextStore(file);
assert.equal(reopened.state.notifications, true);
assert.deepEqual(reopened.state.sources, [source], 'Draft source snapshots must survive session disappearance and reload');
assert.equal(reopened.state.checkpoints.length, 2);
assert.equal(reopened.state.checkpoints[1].nextSteps, fields.nextSteps, 'A new revision must preserve the old checkpoint');
assert.equal(reopened.state.checkpoints[0].parentId, 'checkpoint-1');
assert.deepEqual(validateCheckpoint(JSON.parse(JSON.stringify(original))), original, 'Portable JSON must round-trip');
const markdown = checkpointMarkdown(original);
for (const text of [fields.goal, fields.decisions, fields.verification, fields.nextSteps, 'main', 'abc', ' M src/api.ts']) assert(markdown.includes(text));
assert.throws(() => validateFields({ ...fields, title: '' }));
assert.throws(() => validateFields({ ...fields, goal: 'x'.repeat(20001) }));
assert.throws(() => validateCheckpoint({ ...original, source: { ...source, provider: 'shell' } }));
assert.throws(() => validateCheckpoint({ ...original, terminalExcerpt: 'x'.repeat(12001) }));
const detector = new PromptDetector();
assert.equal(detector.feed('Building project...'), null);
assert.equal(detector.feed('\x1b[32mWould you like to run the following '), null);
assert.equal(detector.feed('command?\x1b[0m').origin, 'inferred');
assert.equal(detector.feed('Would you like to run the following command?'), null, 'Redraws should not duplicate alerts');
detector.input();
assert.equal(detector.feed('Do you want to proceed?').origin, 'inferred');
detector.reset();
assert.equal(detector.feed('\x1b]9;Agent turn'), null);
assert.equal(detector.feed(' complete\x07').origin, 'terminal-notification');
assert.equal(detector.feed('Do you want to proceed?').origin, 'inferred', 'A previous notification must not mask a later prompt');
detector.reset();
assert.equal(detector.feed('\x1b]9;4;1;50\x07'), null, 'Progress OSC must not become a notification');
assert.equal(plainText('\x1b]0;private title\x07\x1b[31mHello\x1b[0m\r\nworld'), 'Hello\nworld');
fs.writeFileSync(file, '{damaged');
const recovered = new ContextStore(file);
assert(recovered.state.checkpoints.length >= 1);
assert(fs.readdirSync(directory).some(name => name.includes('.damaged-')));
assert.doesNotThrow(() => JSON.parse(fs.readFileSync(file, 'utf8')));
// Only generated test files are removed; the caller's directories are untouched.
for (const name of fs.readdirSync(directory)) fs.unlinkSync(path.join(directory, name));
fs.rmdirSync(directory);
console.log('Context checks passed: durable queue, manual/automatic resolution, immutable revisions, reload, JSON round-trip, Markdown, validation, split terminal signals, deduplication, and backup recovery.');
