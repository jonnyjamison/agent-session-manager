// Integration check using the real Electron main/preload/renderer with isolated data.
const { app, BrowserWindow, clipboard, dialog } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'asm-smoke-'));
app.setPath('userData', dataDir);
const fixture = { id: 'smoke-session', name: 'Smoke project', provider: 'codex', cwd: dataDir, status: 'stopped', createdAt: new Date().toISOString() };
fs.writeFileSync(path.join(dataDir, 'workspace.json'), JSON.stringify({ sessions: [fixture], activeId: fixture.id }));
const clipboardBefore = clipboard.readText();
const errors = [];
const watchdog = setTimeout(() => { console.error('Desktop smoke timed out'); app.exit(1); }, 60000);
app.on('web-contents-created', (_event, contents) => { contents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); }); });
require('../dist-electron/main.js');
app.whenReady().then(async () => {
  let win;
  const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
  const js = code => win.webContents.executeJavaScript(code);
  const wait = async predicate => { for (let i = 0; i < 120; i++) { if (await js(predicate)) return; await delay(100); } throw new Error(`UI condition timed out: ${predicate}`); };
  const click = label => js(`(() => { const button = [...document.querySelectorAll('button')].find(b => b.textContent.trim() === ${JSON.stringify(label)}); if (!button) throw new Error('Button missing: ' + ${JSON.stringify(label)}); button.click(); })()`);
  const fill = (id, value) => js(`(() => { const input = document.getElementById(${JSON.stringify(id)}); const prototype = input.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(input, ${JSON.stringify(value)}); input.dispatchEvent(new Event('input', { bubbles: true })); })()`);
  try {
    while (!(win = BrowserWindow.getAllWindows()[0])) await delay(50);
    await wait(`document.body.textContent.includes('Save checkpoint')`);
    assert.equal(win.webContents.getLastWebPreferences().contextIsolation, true);
    assert.equal(win.webContents.getLastWebPreferences().sandbox, true);
    assert.equal(await js(`typeof window.require`), 'undefined');
    await js(`window.sessions.flag('smoke-session', 'Review timeout behavior')`);
    await js(`[...document.querySelectorAll('.workspace-tools button')].find(b => b.textContent.startsWith('Needs me')).click()`);
    await wait(`!!document.querySelector('.attention-card')`);
    assert(await js(`document.body.textContent.includes('Review timeout behavior')`));
    await click('Mark resolved');
    await wait(`!document.querySelector('.attention-card')`);
    await js(`document.querySelector('.session').click()`);
    await wait(`!!document.querySelector('.source-tools')`);
    await click('Save checkpoint');
    await wait(`!!document.getElementById('checkpoint-title')`);
    await fill('checkpoint-title', 'Smoke handover');
    await fill('checkpoint-goal', 'Preserve the original task and acceptance criteria.');
    await fill('checkpoint-progress', 'UI smoke check in progress.');
    await fill('checkpoint-nextSteps', 'Review the saved handover.');
    await fill('checkpoint-verification', 'Desktop flow exercised; no provider request sent.');
    await js(`window.sessions.remove('smoke-session')`);
    await js(`[...document.querySelectorAll('.workspace-tools button')].find(b => b.textContent.startsWith('Needs me')).click()`);
    await js(`[...document.querySelectorAll('.workspace-tools button')].find(b => b.textContent.startsWith('Context library')).click()`);
    await wait(`!!document.querySelector('.draft-list button')`);
    await js(`document.querySelector('.draft-list button').click()`);
    await wait(`!!document.getElementById('checkpoint-title')`);
    assert.equal(await js(`document.getElementById('checkpoint-progress').value`), 'UI smoke check in progress.');
    await js(`document.querySelector('.checkpoint-editor button.primary-action').click()`);
    await wait(`!!document.querySelector('.checkpoint-preview')`);
    let state = await js(`window.sessions.context()`);
    assert.equal(state.checkpoints.length, 1, 'A draft remains saveable after its original managed session is removed');
    assert.equal(state.checkpoints[0].goal, 'Preserve the original task and acceptance criteria.');
    assert.equal(state.checkpoints[0].terminalExcerpt, null);
    await click('Copy handover');
    await wait(`document.body.textContent.includes('Markdown handover copied')`);
    assert(clipboard.readText().includes('Review the saved handover.'));
    const exportPath = path.join(dataDir, 'export.json');
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: exportPath });
    await js(`window.sessions.exportCheckpoint(${JSON.stringify(state.checkpoints[0].id)}, 'json')`);
    assert.equal(JSON.parse(fs.readFileSync(exportPath, 'utf8')).format, 'agent-session-checkpoint');
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [exportPath] });
    dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false });
    const imported = await js(`window.sessions.importCheckpoint()`);
    assert.notEqual(imported.id, state.checkpoints[0].id);
    await click('Create revision');
    await wait(`!!document.getElementById('checkpoint-title')`);
    await fill('checkpoint-nextSteps', 'Continue from the revised handover.');
    await js(`document.querySelector('.checkpoint-editor button.primary-action').click()`);
    await wait(`!!document.querySelector('.checkpoint-preview')`);
    state = await js(`window.sessions.context()`);
    assert.equal(state.checkpoints.length, 3);
    assert(state.checkpoints.some(c => c.parentId));
    assert.equal(state.checkpoints.find(c => c.id === state.checkpoints[0].parentId).nextSteps, 'Review the saved handover.');
    await js(`window.sessions.notifications(true)`);
    win.webContents.reload();
    await wait(`!!document.querySelector('.workspace-tools')`);
    await js(`[...document.querySelectorAll('.workspace-tools button')].find(b => b.textContent.startsWith('Context library')).click()`);
    await wait(`document.querySelectorAll('.checkpoint-list>button').length === 3`);
    assert.equal((await js(`window.sessions.context()`)).notifications, true);
    await js(`document.querySelector('.checkpoint-list>button').click()`);
    await wait(`!!document.querySelector('.checkpoint-preview')`);
    const output = path.join(process.cwd(), '.scratch'); fs.mkdirSync(output, { recursive: true });
    fs.writeFileSync(path.join(output, 'checkpoint-preview.png'), (await win.webContents.capturePage()).toPNG());
    assert.deepEqual(errors, [], 'Renderer should not log errors');
    console.log('Desktop integration passed: isolated renderer, manual attention/resolution, draft restoration, checkpoint save/revision, clipboard handover, JSON export/import, and reload persistence.');
    console.log(`Isolated data: ${dataDir}`);
    clipboard.writeText(clipboardBefore); clearTimeout(watchdog); app.exit(0);
  } catch (error) { console.error(error); console.error(errors); clipboard.writeText(clipboardBefore); clearTimeout(watchdog); app.exit(1); }
});
